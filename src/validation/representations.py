"""Validate final puzzle CSV files and PyG graph representations.

Purpose:
    Check post-preprocessing invariants before model training.
Input:
    data/final/puzzles/*.csv, artifacts/move_*.json, and data/pyg shards.
Output:
    Readable validation report printed to stdout.
Run:
    python3 -m src.validation.representations
    python3 -m src.validation.representations --csv-sample 1000 --graph-sample 500
"""

from pathlib import Path
import argparse
import json
import random

import chess
import pandas as pd
import torch
from torch_geometric.loader import DataLoader

from src.graph.pyg_dataset import (
    OUTPUT_DIR,
    load_pyg_dataset,
)

PUZZLE_SPLITS = {
    "train": Path("data/final/puzzles/train.csv"),
    "val": Path("data/final/puzzles/val.csv"),
    "test": Path("data/final/puzzles/test.csv"),
}

PYG_ROOT = OUTPUT_DIR
PYG_SPLITS = ("train", "val", "test")

MOVE_TO_IDX_PATH = Path("resources/move_encoder/move_to_idx.json")
IDX_TO_MOVE_PATH = Path("resources/move_encoder/idx_to_move.json")
MOVE_STATS_PATH = Path("resources/move_encoder/move_encoder_stats.json")

REQUIRED_PUZZLE_COLUMNS = [
    "OriginalFEN",
    "FEN",
    "Moves",
    "TargetMove",
]

EXPECTED_NODE_SHAPE = (64, 15)
EXPECTED_EDGE_FEATURE_DIM = 5
EXPECTED_GLOBAL_SHAPE = (1, 4)


def parse_args():
    """Parse command-line options.

    Parameters:
        None.
    Returns:
        argparse.Namespace with sample sizes and random seed.
    Side effects:
        Reads command-line arguments from sys.argv.
    """

    parser = argparse.ArgumentParser(
        description="Validate chess CSV and PyG representations."
    )
    parser.add_argument(
        "--csv-sample",
        type=int,
        default=1000,
        help="Rows sampled per puzzle CSV split.",
    )
    parser.add_argument(
        "--graph-sample",
        type=int,
        default=500,
        help="Graphs sampled per PyG split.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed used for deterministic sampling.",
    )

    return parser.parse_args()


def sample_indices(total, sample_size, seed):
    """Return deterministic sample indices.

    Parameters:
        total: Total number of records.
        sample_size: Maximum number of records to sample.
        seed: Random seed.
    Returns:
        Sorted list of sampled indices.
    Side effects:
        None.
    """

    if total <= 0 or sample_size <= 0:
        return []

    count = min(
        total,
        sample_size
    )

    rng = random.Random(seed)
    return sorted(
        rng.sample(
            range(total),
            count
        )
    )


def fen_matches(actual_fen, expected_fen):
    """Compare two FEN positions including counters.

    Parameters:
        actual_fen: FEN generated by python-chess.
        expected_fen: FEN stored in the CSV.
    Returns:
        True when the normalized board states are identical.
    Side effects:
        None.
    """

    try:
        return chess.Board(actual_fen).fen() == chess.Board(expected_fen).fen()
    except Exception:
        return False


def validate_puzzle_row(row):
    """Validate one final puzzle CSV row.

    Parameters:
        row: Pandas row with OriginalFEN, FEN, Moves, and TargetMove.
    Returns:
        List of failed invariant names.
    Side effects:
        None.
    """

    failures = []
    moves = str(row.Moves).split()

    try:
        board = chess.Board(row.OriginalFEN)
    except Exception:
        return ["invalid OriginalFEN"]

    if len(moves) < 2:
        return ["setup move illegal", "TargetMove mismatch", "target illegal"]

    try:
        setup_move = chess.Move.from_uci(moves[0])
    except Exception:
        return ["setup move illegal"]

    if setup_move not in board.legal_moves:
        failures.append("setup move illegal")
    else:
        board.push(setup_move)
        if not fen_matches(board.fen(), row.FEN):
            failures.append("FEN mismatch")

    if str(row.TargetMove) != moves[1]:
        failures.append("TargetMove mismatch")

    try:
        target_board = chess.Board(row.FEN)
        target_move = chess.Move.from_uci(str(row.TargetMove))
        if target_move not in target_board.legal_moves:
            failures.append("target illegal")
    except Exception:
        failures.append("target illegal")

    return failures


def validate_csv_split(name, path, sample_size, seed):
    """Validate one final puzzle CSV split.

    Parameters:
        name: Split name.
        path: CSV path.
        sample_size: Maximum rows to validate.
        seed: Sampling seed.
    Returns:
        Dict with status and error counts.
    Side effects:
        Reads path from disk.
    """

    result = {
        "name": name,
        "path": path,
        "passed": True,
        "total_rows": 0,
        "checked_rows": 0,
        "missing_columns": [],
        "invalid OriginalFEN": 0,
        "setup move illegal": 0,
        "FEN mismatch": 0,
        "TargetMove mismatch": 0,
        "target illegal": 0,
    }

    if not path.exists():
        result["passed"] = False
        result["missing_file"] = True
        return result

    df = pd.read_csv(path)
    result["total_rows"] = len(df)

    missing_columns = [
        column
        for column in REQUIRED_PUZZLE_COLUMNS
        if column not in df.columns
    ]
    result["missing_columns"] = missing_columns

    if missing_columns:
        result["passed"] = False
        return result

    indices = sample_indices(
        len(df),
        sample_size,
        seed
    )
    result["checked_rows"] = len(indices)

    for _, row in df.iloc[indices].iterrows():
        for failure in validate_puzzle_row(row):
            result[failure] += 1

    failed_checks = [
        key
        for key in (
            "invalid OriginalFEN",
            "setup move illegal",
            "FEN mismatch",
            "TargetMove mismatch",
            "target illegal",
        )
        if result[key] > 0
    ]
    result["passed"] = not failed_checks

    return result


def load_json(path):
    """Load a JSON file.

    Parameters:
        path: JSON path.
    Returns:
        Parsed JSON object.
    Side effects:
        Reads path from disk.
    """

    with open(
        path,
        "r",
        encoding="utf-8"
    ) as file:
        return json.load(file)


def compute_oov(csv_path, move_to_idx):
    """Compute OOV target statistics for one CSV split.

    Parameters:
        csv_path: Puzzle CSV path.
        move_to_idx: Training-only move vocabulary.
    Returns:
        Dict with count, total, and percentage.
    Side effects:
        Reads csv_path from disk.
    """

    df = pd.read_csv(csv_path)
    targets = df["TargetMove"].dropna().astype(str)
    oov_count = int(
        (~targets.isin(move_to_idx)).sum()
    )
    total = len(targets)

    return {
        "count": oov_count,
        "total": total,
        "percentage": (
            oov_count / total * 100
            if total
            else 0.0
        ),
    }


def extract_recorded_oov(stats, split):
    """Find recorded OOV stats for one split.

    Parameters:
        stats: Parsed move_encoder_stats.json object.
        split: Split name, usually val or test.
    Returns:
        Dict with count, total, and percentage, or None if unavailable.
    Side effects:
        None.
    """

    for item in stats.get("oov_stats", []):
        if item.get("split") == split:
            return {
                "count": item.get("oov_targets"),
                "total": item.get("input_targets"),
                "percentage": item.get("oov_percentage"),
            }

    return None


def validate_move_encoder():
    """Validate move vocabulary artifacts and OOV statistics.

    Parameters:
        None.
    Returns:
        Dict with encoder status and OOV summaries.
    Side effects:
        Reads move encoder JSON files and puzzle CSV files from disk.
    """

    result = {
        "passed": True,
        "errors": [],
        "vocab_size": 0,
        "oov": {},
    }

    required_paths = [
        MOVE_TO_IDX_PATH,
        IDX_TO_MOVE_PATH,
        MOVE_STATS_PATH,
    ]

    for path in required_paths:
        if not path.exists():
            result["errors"].append(
                f"missing file: {path}"
            )

    if result["errors"]:
        result["passed"] = False
        return result

    move_to_idx = load_json(MOVE_TO_IDX_PATH)
    idx_to_move_raw = load_json(IDX_TO_MOVE_PATH)
    stats = load_json(MOVE_STATS_PATH)
    idx_to_move = {
        int(index): move
        for index, move in idx_to_move_raw.items()
    }

    result["vocab_size"] = len(move_to_idx)

    if len(set(move_to_idx)) != len(move_to_idx):
        result["errors"].append("duplicate moves in move_to_idx")

    indices = list(move_to_idx.values())
    if len(set(indices)) != len(indices):
        result["errors"].append("duplicate indices in move_to_idx")

    if len(set(idx_to_move)) != len(idx_to_move):
        result["errors"].append("duplicate indices in idx_to_move")

    if len(set(idx_to_move.values())) != len(idx_to_move):
        result["errors"].append("duplicate moves in idx_to_move")

    for move, index in move_to_idx.items():
        if idx_to_move.get(int(index)) != move:
            result["errors"].append(
                f"mapping mismatch: {move} -> {index}"
            )
            break

    if PUZZLE_SPLITS["train"].exists():
        train_targets = set(
            pd.read_csv(PUZZLE_SPLITS["train"])["TargetMove"]
            .dropna()
            .astype(str)
        )
        if set(move_to_idx) != train_targets:
            result["errors"].append(
                "vocabulary does not match current train TargetMove values"
            )
    else:
        result["errors"].append(
            f"missing train CSV: {PUZZLE_SPLITS['train']}"
        )

    for split in ("val", "test"):
        csv_path = PUZZLE_SPLITS[split]
        if not csv_path.exists():
            result["errors"].append(
                f"missing {split} CSV: {csv_path}"
            )
            continue

        current = compute_oov(
            csv_path,
            move_to_idx
        )
        recorded = extract_recorded_oov(
            stats,
            split
        )
        result["oov"][split] = {
            "current": current,
            "recorded": recorded,
        }

        if recorded is None:
            result["errors"].append(
                f"missing recorded OOV stats for {split}"
            )
            continue

        if (
            current["count"] != recorded["count"]
            or current["total"] != recorded["total"]
            or round(current["percentage"], 6)
            != round(float(recorded["percentage"]), 6)
        ):
            result["errors"].append(
                f"OOV stats mismatch for {split}"
            )

    result["passed"] = not result["errors"]
    return result


def load_graphs(split, root=PYG_ROOT):
    """Load a PyG split from sharded or legacy storage.

    Parameters:
        split: Split name.
        root: PyG dataset root.
    Returns:
        Dataset-like object for one split.
    Side effects:
        Reads manifest metadata or legacy graph data from disk.
    """

    return load_pyg_dataset(
        root=root,
        split=split,
    )


def tensor_has_nan_or_inf(tensor):
    """Check whether a tensor contains NaN or Inf values.

    Parameters:
        tensor: Torch tensor.
    Returns:
        True when tensor has at least one non-finite value.
    Side effects:
        None.
    """

    return bool(
        torch.isnan(tensor).any()
        or torch.isinf(tensor).any()
    )


def validate_graph(graph):
    """Validate one PyG graph object.

    Parameters:
        graph: torch_geometric.data.Data instance.
    Returns:
        Tuple of failed invariant names and multilabel edge counters.
    Side effects:
        None.
    """

    failures = []
    multilabel_counts = {
        "single": 0,
        "two": 0,
        "three_plus": 0,
    }

    if not hasattr(graph, "x") or graph.x.ndim != 2:
        failures.append("x.ndim != 2")
    elif tuple(graph.x.shape) != EXPECTED_NODE_SHAPE:
        failures.append("x.shape != [64, 15]")
    elif tensor_has_nan_or_inf(graph.x):
        failures.append("x contains NaN/Inf")

    if not hasattr(graph, "edge_index") or graph.edge_index.ndim != 2:
        failures.append("edge_index.ndim != 2")
    elif graph.edge_index.shape[0] != 2:
        failures.append("edge_index.shape[0] != 2")
    elif graph.edge_index.numel() > 0:
        if int(graph.edge_index.min()) < 0 or int(graph.edge_index.max()) > 63:
            failures.append("edge index outside [0, 63]")

        pairs = [
            tuple(pair)
            for pair in graph.edge_index.t().tolist()
        ]
        if len(set(pairs)) != len(pairs):
            failures.append("duplicate edge")

    if not hasattr(graph, "edge_attr") or graph.edge_attr.ndim != 2:
        failures.append("edge_attr.ndim != 2")
    elif graph.edge_attr.shape[1] != EXPECTED_EDGE_FEATURE_DIM:
        failures.append("edge_attr.shape[1] != 5")
    else:
        if (
            hasattr(graph, "edge_index")
            and graph.edge_attr.shape[0] != graph.edge_index.shape[1]
        ):
            failures.append("edge_attr rows != edge count")

        if tensor_has_nan_or_inf(graph.edge_attr):
            failures.append("edge_attr contains NaN/Inf")

        is_binary = torch.logical_or(
            graph.edge_attr == 0,
            graph.edge_attr == 1
        ).all()
        if not bool(is_binary):
            failures.append("edge_attr not binary")

        active_counts = graph.edge_attr.sum(dim=1)
        if bool((active_counts < 1).any()):
            failures.append("edge without active label")

        multilabel_counts["single"] += int(
            (active_counts == 1).sum()
        )
        multilabel_counts["two"] += int(
            (active_counts == 2).sum()
        )
        multilabel_counts["three_plus"] += int(
            (active_counts >= 3).sum()
        )

    if not hasattr(graph, "global_features"):
        failures.append("missing global_features")
    elif tuple(graph.global_features.shape) != EXPECTED_GLOBAL_SHAPE:
        failures.append("global_features.shape != [1, 4]")
    elif tensor_has_nan_or_inf(graph.global_features):
        failures.append("global_features contains NaN/Inf")

    if not hasattr(graph, "y"):
        failures.append("missing y")
    elif graph.y.numel() != 1:
        failures.append("y is not graph-level scalar")

    return failures, multilabel_counts


def merge_counts(target, source):
    """Add integer counts from source into target.

    Parameters:
        target: Mutable count dictionary.
        source: Count dictionary to add.
    Returns:
        None.
    Side effects:
        Mutates target in place.
    """

    for key, value in source.items():
        target[key] += value


def validate_pyg_split(name, sample_size, seed):
    """Validate a sampled PyG split.

    Parameters:
        name: Split name.
        sample_size: Maximum graphs to validate.
        seed: Sampling seed.
    Returns:
        Dict with status, failures, and multilabel counts.
    Side effects:
        Reads graph samples from disk through the dataset loader.
    """

    result = {
        "name": name,
        "path": PYG_ROOT,
        "passed": True,
        "total_graphs": 0,
        "checked_graphs": 0,
        "failures": {},
        "multilabel": {
            "single": 0,
            "two": 0,
            "three_plus": 0,
        },
        "graphs": [],
    }

    try:
        graphs = load_graphs(name)
    except (FileNotFoundError, ValueError) as error:
        result["passed"] = False
        result["failures"][str(error)] = 1
        return result

    result["total_graphs"] = len(graphs)
    result["graphs"] = graphs

    indices = sample_indices(
        len(graphs),
        sample_size,
        seed
    )
    result["checked_graphs"] = len(indices)

    for index in indices:
        failures, multilabel_counts = validate_graph(
            graphs[index]
        )
        merge_counts(
            result["multilabel"],
            multilabel_counts
        )

        for failure in failures:
            result["failures"][failure] = (
                result["failures"].get(failure, 0) + 1
            )

    result["passed"] = not result["failures"]
    return result


def validate_csv_pyg_consistency(split, csv_path, graphs, sample_size, seed):
    """Validate graph targets against CSV rows when order is preserved.

    Parameters:
        split: Split name.
        csv_path: Puzzle CSV path.
        graphs: Loaded graph list for the same split.
        sample_size: Maximum records to validate.
        seed: Sampling seed.
    Returns:
        Dict with status and failure counts.
    Side effects:
        Reads csv_path and move_to_idx.json from disk.
    """

    result = {
        "split": split,
        "passed": True,
        "checked": 0,
        "failures": {},
        "note": "",
    }

    if not csv_path.exists() or not MOVE_TO_IDX_PATH.exists():
        result["passed"] = False
        result["failures"]["missing CSV or move encoder"] = 1
        return result

    df = pd.read_csv(csv_path)
    move_to_idx = load_json(MOVE_TO_IDX_PATH)

    if len(graphs) > len(df):
        result["passed"] = False
        result["failures"]["more graphs than CSV rows"] = 1
        return result

    if len(graphs) != len(df):
        result["note"] = (
            "Graph count differs from CSV rows; checking source_row_index "
            "metadata when available because OOV/invalid rows may be skipped."
        )

    limit = min(
        len(graphs),
        len(df),
        sample_size
    )
    indices = sample_indices(
        limit,
        limit,
        seed
    )
    result["checked"] = len(indices)

    for index in indices:
        graph = graphs[index]
        source_row_index = index
        if hasattr(graph, "source_row_index"):
            source_row_index = int(graph.source_row_index.item())

        if source_row_index < 0 or source_row_index >= len(df):
            result["failures"]["source_row_index out of range"] = (
                result["failures"].get("source_row_index out of range", 0) + 1
            )
            continue

        row = df.iloc[source_row_index]
        target_move = str(row.TargetMove)

        if target_move not in move_to_idx:
            result["failures"]["target OOV"] = (
                result["failures"].get("target OOV", 0) + 1
            )
            continue

        if int(graph.y.item()) != int(move_to_idx[target_move]):
            result["failures"]["target y mismatch"] = (
                result["failures"].get("target y mismatch", 0) + 1
            )

        try:
            chess.Board(row.FEN)
        except Exception:
            result["failures"]["CSV FEN invalid"] = (
                result["failures"].get("CSV FEN invalid", 0) + 1
            )

        if hasattr(graph, "x") and graph.x.shape[0] != 64:
            result["failures"]["graph does not have 64 nodes"] = (
                result["failures"].get(
                    "graph does not have 64 nodes",
                    0
                )
                + 1
            )

    result["passed"] = not result["failures"]
    return result


def validate_batching(graphs_by_split):
    """Validate PyG DataLoader batching on a small graph batch.

    Parameters:
        graphs_by_split: Dict of split name to loaded graph list.
    Returns:
        Dict with status and failure counts.
    Side effects:
        Builds one in-memory DataLoader batch.
    """

    result = {
        "passed": True,
        "failures": {},
        "batch_size": 0,
    }

    graphs = []
    for split_graphs in graphs_by_split.values():
        for index in range(min(8, len(split_graphs))):
            graphs.append(split_graphs[index])
            if len(graphs) >= 8:
                break
        if len(graphs) >= 8:
            break

    graphs = graphs[:8]
    result["batch_size"] = len(graphs)

    if not graphs:
        result["passed"] = False
        result["failures"]["no graphs available"] = 1
        return result

    batch = next(
        iter(
            DataLoader(
                graphs,
                batch_size=len(graphs)
            )
        )
    )

    if batch.x.shape[0] != 64 * len(graphs):
        result["failures"]["batch.x row count mismatch"] = 1

    if batch.edge_index.ndim != 2 or batch.edge_index.shape[0] != 2:
        result["failures"]["batch.edge_index invalid"] = 1
    elif batch.edge_index.numel() > 0:
        max_node_index = 64 * len(graphs) - 1
        if int(batch.edge_index.min()) < 0 or int(batch.edge_index.max()) > max_node_index:
            result["failures"]["batch edge index out of range"] = 1

    if batch.edge_attr.shape[0] != batch.edge_index.shape[1]:
        result["failures"]["batch edge_attr row mismatch"] = 1

    if tuple(batch.global_features.shape) != (len(graphs), 4):
        result["failures"]["batch.global_features shape mismatch"] = 1

    if batch.y.numel() != len(graphs):
        result["failures"]["batch.y size mismatch"] = 1

    result["passed"] = not result["failures"]
    return result


def format_status(passed):
    """Convert a boolean status to PASS/FAIL.

    Parameters:
        passed: Boolean validation result.
    Returns:
        PASS or FAIL string.
    Side effects:
        None.
    """

    return "PASS" if passed else "FAIL"


def print_report(csv_results, encoder_result, pyg_results, consistency_results, batching_result):
    """Print the final validation report.

    Parameters:
        csv_results: Dict of CSV split validation results.
        encoder_result: Move encoder validation result.
        pyg_results: Dict of PyG split validation results.
        consistency_results: Dict of CSV-to-PyG checks.
        batching_result: Batching validation result.
    Returns:
        List of failed invariant descriptions.
    Side effects:
        Writes the report to stdout.
    """

    failed_invariants = []

    print("\nCSV SEMANTICS")
    for split, result in csv_results.items():
        print(f"- {split}: {format_status(result['passed'])}")
        print(
            f"  rows={result['total_rows']:,}, "
            f"checked={result['checked_rows']:,}"
        )
        for key in (
            "invalid OriginalFEN",
            "setup move illegal",
            "FEN mismatch",
            "TargetMove mismatch",
            "target illegal",
        ):
            print(f"  {key}: {result[key]}")
            if result[key]:
                failed_invariants.append(f"{split} CSV: {key}")
        if result.get("missing_columns"):
            failed_invariants.append(
                f"{split} CSV missing columns: {result['missing_columns']}"
            )
        if result.get("missing_file"):
            failed_invariants.append(f"{split} CSV missing file")

    print("\nMOVE ENCODER")
    print(f"- {format_status(encoder_result['passed'])}")
    print(f"  vocab size: {encoder_result['vocab_size']:,}")
    for split in ("val", "test"):
        oov = encoder_result["oov"].get(split, {})
        current = oov.get("current")
        if current:
            print(
                f"  OOV {split}: {current['count']:,} / "
                f"{current['total']:,} ({current['percentage']:.2f}%)"
            )
        else:
            print(f"  OOV {split}: unavailable")
    for error in encoder_result["errors"]:
        failed_invariants.append(f"move encoder: {error}")
        print(f"  error: {error}")

    print("\nPYG REPRESENTATION")
    multilabel_totals = {
        "single": 0,
        "two": 0,
        "three_plus": 0,
    }
    for split, result in pyg_results.items():
        print(f"- {split}: {format_status(result['passed'])}")
        print(
            f"  graphs={result['total_graphs']:,}, "
            f"checked={result['checked_graphs']:,}"
        )
        merge_counts(
            multilabel_totals,
            result["multilabel"]
        )
        for failure, count in result["failures"].items():
            failed_invariants.append(
                f"{split} PyG: {failure} ({count})"
            )
            print(f"  {failure}: {count}")

    print("\nCSV <-> PYG")
    for split, result in consistency_results.items():
        print(f"- {split}: {format_status(result['passed'])}")
        print(f"  checked={result['checked']:,}")
        if result["note"]:
            print(f"  note: {result['note']}")
        for failure, count in result["failures"].items():
            failed_invariants.append(
                f"{split} CSV/PyG: {failure} ({count})"
            )
            print(f"  {failure}: {count}")

    print("\nBATCHING")
    print(f"- {format_status(batching_result['passed'])}")
    print(f"  batch size: {batching_result['batch_size']}")
    for failure, count in batching_result["failures"].items():
        failed_invariants.append(
            f"batching: {failure} ({count})"
        )
        print(f"  {failure}: {count}")

    print("\nMULTILABEL EDGES")
    print(f"- single-label: {multilabel_totals['single']:,}")
    print(f"- two-label: {multilabel_totals['two']:,}")
    print(f"- three-or-more-label: {multilabel_totals['three_plus']:,}")

    print("\nFINAL VERDICT:")
    if failed_invariants:
        print("REPRESENTATION_INVALID")
        print("\nFailed invariants:")
        for failure in failed_invariants:
            print(f"- {failure}")
    else:
        print("REPRESENTATION_VALID")

    return failed_invariants


def run_validation(csv_sample=1000, graph_sample=500, seed=42):
    """Run all representation validation checks.

    Parameters:
        csv_sample: Number of CSV rows sampled per split.
        graph_sample: Number of graphs sampled per split.
        seed: Deterministic sampling seed.
    Returns:
        List of failed invariant descriptions.
    Side effects:
        Reads generated datasets/artifacts and prints a report.
    """

    csv_results = {
        split: validate_csv_split(
            split,
            path,
            csv_sample,
            seed
        )
        for split, path in PUZZLE_SPLITS.items()
    }

    encoder_result = validate_move_encoder()

    pyg_results = {
        split: validate_pyg_split(
            split,
            graph_sample,
            seed
        )
        for split in PYG_SPLITS
    }

    graphs_by_split = {
        split: result["graphs"]
        for split, result in pyg_results.items()
    }

    consistency_results = {
        split: validate_csv_pyg_consistency(
            split,
            PUZZLE_SPLITS[split],
            pyg_results[split]["graphs"],
            graph_sample,
            seed
        )
        for split in PYG_SPLITS
    }

    batching_result = validate_batching(
        graphs_by_split
    )

    return print_report(
        csv_results,
        encoder_result,
        pyg_results,
        consistency_results,
        batching_result
    )


def main():
    """Run validation from the command line.

    Parameters:
        None.
    Returns:
        None.
    Side effects:
        Prints validation results and exits with code 1 on failure.
    """

    args = parse_args()
    failed_invariants = run_validation(
        csv_sample=args.csv_sample,
        graph_sample=args.graph_sample,
        seed=args.seed,
    )

    if failed_invariants:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
